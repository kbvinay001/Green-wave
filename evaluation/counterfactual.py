def make_plots(pairs: List[dict], img_dir: Path) -> List[Path]:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    img_dir.mkdir(parents=True, exist_ok=True)
    written = []
    scales = sorted({p["scale"] for p in pairs})

    def across_seeds(scale, mode, *path):
        vals = []
        for p in pairs:
            if p["scale"] != scale:
                continue
            v = p[mode]
            for k in path:
                v = v[k]
            vals.append(v)
        return vals

    def mean_std(scale, mode, *path):
        vals = across_seeds(scale, mode, *path)
        return (statistics.mean(vals),
                statistics.stdev(vals) if len(vals) > 1 else 0.0)

    modes_present = [(m, lbl, c) for m, lbl, c in
                     (("baseline",   "baseline",                 "#b0413e"),
                      ("greenwave",  "green wave (perfect)",     "#3e8e41"),
                      ("closedloop", "closed loop (noisy sensors)", "#d68910"))
                     if m in pairs[0]]

    # The money plot: what preemption is worth as congestion grows
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(11.5, 4.2))
    for mode, label, color in modes_present:
        means, stds = zip(*[mean_std(s, mode, "ev_travel_s") for s in scales])
        ax1.errorbar(scales, means, yerr=stds, label=label, color=color,
                     marker="o", capsize=4, linewidth=1.6)
        cmeans, cstds = zip(*[mean_std(s, mode, "civilians", "mean_time_loss_s")
                              for s in scales])
        ax2.errorbar(scales, cmeans, yerr=cstds, label=label, color=color,
                     marker="o", capsize=4, linewidth=1.6)

    ax1.set_xlabel("traffic demand (x recorded volume)")
    ax1.set_ylabel("EV corridor travel time (s)")
    ax1.set_title("Ambulance through Benz Circle")
    ax1.set_xticks(scales)
    ax1.legend()
    ax2.set_xlabel("traffic demand (x recorded volume)")
    ax2.set_ylabel("mean time loss per civilian (s)")
    ax2.set_title("Cost to everyone else")
    ax2.set_xticks(scales)
    ax2.legend()
    fig.tight_layout()
    p1 = img_dir / "counterfactual_travel_time.png"
    fig.savefig(p1, dpi=130)
    plt.close(fig)
    written.append(p1)

    # Speed trace at the heaviest congestion that completed: the picture
    # that explains the table -- baseline crawls the queue, green wave glides
    heavy = [p for p in pairs if p["scale"] == scales[-1]][0]
    fig, ax = plt.subplots(figsize=(11.5, 3.8))
    for mode, label, color in modes_present:
        tr = heavy[f"_{mode}_trace"]
        t0 = tr[0][0]
        ax.plot([t - t0 for t, _ in tr], [v * 3.6 for _, v in tr],
                label=label, color=color, linewidth=1.4)
        if mode != "baseline" and heavy[mode]["triggered_at"] is not None:
            ax.axvline(heavy[mode]["triggered_at"] - t0, color=color,
                       linestyle=":", linewidth=1.2)
    ax.set_xlabel("seconds since EV entered the network")
    ax.set_ylabel("EV speed (km/h)")
    ax.set_title(f"Ambulance speed, {heavy['scale']:g}x demand (seed {heavy['seed']})")
    ax.legend(loc="upper right")
    fig.tight_layout()
    p2 = img_dir / "counterfactual_ev_speed.png"
    fig.savefig(p2, dpi=130)
    plt.close(fig)
    written.append(p2)

    return written


