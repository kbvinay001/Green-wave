#!/usr/bin/env python3
"""
Counterfactual evaluation -- Green Wave++ (phase 5)

The question that decides whether any of this matters: with the SAME
traffic, the SAME routes and the SAME random seed, how much faster does
the ambulance cross Benz Circle when the green wave fires -- and what
does that cost everyone else?

Two headless SUMO runs per seed:

  baseline    signals run their normal programs; the ambulance fights
              traffic like any other vehicle.
  greenwave   identical world, but once the ambulance closes within
              --trigger-m of the first corridor junction, the same
              SumoController the live system uses fires its ETA cascade
              (all-red clearance -> green hold per junction).

The trigger uses the ambulance's ground-truth position from SUMO, not
the detectors. That isolates "what is preemption worth" from "did the
CRNN hear the siren" -- phases 1-3 already measure the latter.

All numbers come from SUMO's tripinfo output. No assumed cycle times,
no analytical baselines:

  EV         corridor travel time, time stopped, number of stops
  civilians  mean/max time loss, mean waiting time, arrived count

Usage:
    python -m evaluation.counterfactual                    # 3 seeds, headless
    python -m evaluation.counterfactual --seeds 42 --gui
    python -m evaluation.counterfactual --duration 500 --depart 60

Writes:
    outputs/counterfactual/                  per-run cfg + tripinfo (disposable)
    evaluation/results/counterfactual.json   summary numbers (committed)
    docs/img/counterfactual_*.png            plots for the README (committed)
"""

from __future__ import annotations

import argparse
import json
import statistics
import sys
import xml.etree.ElementTree as ET
from pathlib import Path
from typing import Dict, List, Optional, Tuple

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from fusion.route_predictor import RoutePredictor      # noqa: E402
from fusion.sumo_controller import SumoController      # noqa: E402

EV_ID    = "ev_counterfactual"
EV_TYPE  = "ambulance_eval"
EV_ROUTE = "ev_benz_corridor_eval"
NET_DIR  = ROOT / "sim" / "nets" / "benz_circle"
RUN_DIR  = ROOT / "outputs" / "counterfactual"


# ---------------------------------------------------------------------------
# Run configuration
# ---------------------------------------------------------------------------

def write_eval_routes(out_dir: Path, net_dir: Path = NET_DIR) -> Path:
    """
    The live system's ambulance (ev.rou.xml) carries SUMO's bluelight
    device: surrounding cars part into a perfect rescue lane and the EV
    drives through red when it judges that safe. On the arterials this
    project targets there is no room to part and nobody models Indian
    rush-hour as 'ideal yielding' -- and with bluelight on, the measured
    preemption benefit is pure noise anyway (the EV ignores the very
    signals we control; at 3x demand it even collides and teleports).

    So the eval gets its own EV: same physics, same route, same 30%-over
    siren speedFactor -- but it obeys signals and queues like everything
    else. What the green wave removes is then exactly what we measure.
    """
    src = ET.parse(net_dir / "ev.rou.xml").getroot()
    edges = src.find(f"route[@id='ev_benz_corridor']").get("edges")
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / "eval_ev.rou.xml"
    path.write_text(f"""<routes>
    <!-- generated by evaluation.counterfactual: bluelight-free EV -->
    <vType id="{EV_TYPE}" vClass="emergency" accel="3.0" decel="5.0"
           length="6.5" maxSpeed="22.0" speedFactor="1.3" guiShape="emergency"/>
    <route id="{EV_ROUTE}" edges="{edges}"/>
</routes>
""")
    return path


def write_run_cfg(out_dir: Path, name: str, seed: int, scale: float = 1.0,
                  net_dir: Path = NET_DIR) -> Tuple[Path, Path]:
    """
    One .sumocfg per run, with absolute paths so it works from anywhere,
    the seed pinned, demand scaled (SUMO clones route-file traffic by
    `scale`), and tripinfo pointed at a sibling file. Returns
    (cfg_path, tripinfo_path).
    """
    out_dir.mkdir(parents=True, exist_ok=True)
    cfg_path  = out_dir / f"{name}.sumocfg"
    trip_path = out_dir / f"{name}.tripinfo.xml"
    routes    = [net_dir / "background.rou.xml",
                 write_eval_routes(out_dir, net_dir)]
    cfg_path.write_text(f"""<configuration>
    <input>
        <net-file value="{(net_dir / 'benz.net.xml').resolve()}"/>
        <route-files value="{','.join(str(r.resolve()) for r in routes)}"/>
    </input>
    <time>
        <begin value="0"/>
        <step-length value="0.1"/>
    </time>
    <random_number>
        <seed value="{seed}"/>
    </random_number>
    <output>
        <tripinfo-output value="{trip_path.resolve()}"/>
    </output>
    <processing>
        <scale value="{scale}"/>
        <time-to-teleport value="-1"/>
        <ignore-route-errors value="true"/>
    </processing>
    <report>
        <no-step-log value="true"/>
        <duration-log.disable value="true"/>
    </report>
</configuration>
""")
    return cfg_path, trip_path


