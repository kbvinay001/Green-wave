def write_eval_routes(out_dir: Path, net_dir: Path = NET_DIR) -> Path:
    """
    The live system's ambulance (ev.rou.xml) carries SUMO's bluelight
    device: surrounding cars part into a perfect rescue lane and the EV
    drives through red when it judges that safe. On the arterials this
    project targets there is no room to part and nobody models Indian
    rush-hour as 'ideal yielding' -- and with bluelight on, the measured
    preemption benefit is pure noise anyway (the EV ignores the very
    signals we control; at 3x demand it even collides and teleports).

    So the eval gets its own EV: same physics, same route, same 30%-over
    siren speedFactor -- but it obeys signals and queues like everything
    else. What the green wave removes is then exactly what we measure.
    """
    src = ET.parse(net_dir / "ev.rou.xml").getroot()
    edges = src.find(f"route[@id='ev_benz_corridor']").get("edges")
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / "eval_ev.rou.xml"
    path.write_text(f"""<routes>
    <!-- generated by evaluation.counterfactual: bluelight-free EV -->
    <vType id="{EV_TYPE}" vClass="emergency" accel="3.0" decel="5.0"
           length="6.5" maxSpeed="22.0" speedFactor="1.3" guiShape="emergency"/>
    <route id="{EV_ROUTE}" edges="{edges}"/>
</routes>
""")
    return path


def write_run_cfg(out_dir: Path, name: str, seed: int, scale: float = 1.0,
                  net_dir: Path = NET_DIR) -> Tuple[Path, Path]:
    """
    One .sumocfg per run, with absolute paths so it works from anywhere,
    the seed pinned, demand scaled (SUMO clones route-file traffic by
    `scale`), and tripinfo pointed at a sibling file. Returns
    (cfg_path, tripinfo_path).
    """
    out_dir.mkdir(parents=True, exist_ok=True)
    cfg_path  = out_dir / f"{name}.sumocfg"
    trip_path = out_dir / f"{name}.tripinfo.xml"
    routes    = [net_dir / "background.rou.xml",
                 write_eval_routes(out_dir, net_dir)]
    cfg_path.write_text(f"""<configuration>
    <input>
        <net-file value="{(net_dir / 'benz.net.xml').resolve()}"/>
        <route-files value="{','.join(str(r.resolve()) for r in routes)}"/>
    </input>
    <time>
        <begin value="0"/>
        <step-length value="0.1"/>
    </time>
    <random_number>
        <seed value="{seed}"/>
    </random_number>
    <output>
        <tripinfo-output value="{trip_path.resolve()}"/>
    </output>
    <processing>
        <scale value="{scale}"/>
        <time-to-teleport value="-1"/>
        <ignore-route-errors value="true"/>
    </processing>
    <report>
        <no-step-log value="true"/>
        <duration-log.disable value="true"/>
    </report>
</configuration>
""")
    return cfg_path, trip_path


