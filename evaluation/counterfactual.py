def parse_tripinfo(path: Path, ev_id: str = EV_ID) -> Tuple[Optional[dict], List[dict]]:
    """Split a tripinfo file into (ev_record, civilian_records)."""
    ev, civilians = None, []
    for ti in ET.parse(path).getroot().iter("tripinfo"):
        rec = {
            "id":           ti.get("id"),
            "duration":     float(ti.get("duration")),
            "timeLoss":     float(ti.get("timeLoss")),
            "waitingTime":  float(ti.get("waitingTime")),
            "departDelay":  float(ti.get("departDelay", 0.0)),
        }
        if rec["id"] == ev_id:
            ev = rec
        else:
            civilians.append(rec)
    return ev, civilians


def stops_from_trace(trace: List[Tuple[float, float]],
                     threshold_mps: float = 0.3) -> Tuple[int, float]:
    """(number of distinct stops, total seconds stopped) from a speed trace."""
    stops, stopped_time, was_stopped = 0, 0.0, False
    for i, (t, v) in enumerate(trace):
        stopped = v < threshold_mps
        if stopped and not was_stopped:
            stops += 1
        if stopped and i + 1 < len(trace):
            stopped_time += trace[i + 1][0] - t
        was_stopped = stopped
    return stops, round(stopped_time, 1)


def civilian_summary(civilians: List[dict]) -> dict:
    if not civilians:
        return {"arrived": 0, "mean_time_loss_s": 0.0,
                "max_time_loss_s": 0.0, "mean_waiting_s": 0.0}
    losses = [c["timeLoss"] for c in civilians]
    waits  = [c["waitingTime"] for c in civilians]
    return {
        "arrived":          len(civilians),
        "mean_time_loss_s": round(statistics.mean(losses), 1),
        "max_time_loss_s":  round(max(losses), 1),
        "mean_waiting_s":   round(statistics.mean(waits), 1),
    }


