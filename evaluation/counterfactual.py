#!/usr/bin/env python3
"""
Counterfactual evaluation -- Green Wave++ (phase 5)

The question that decides whether any of this matters: with the SAME
traffic, the SAME routes and the SAME random seed, how much faster does
the ambulance cross Benz Circle when the green wave fires -- and what
does that cost everyone else?

Two headless SUMO runs per seed:

  baseline    signals run their normal programs; the ambulance fights
              traffic like any other vehicle.
  greenwave   identical world, but once the ambulance closes within
              --trigger-m of the first corridor junction, the same
              SumoController the live system uses fires its ETA cascade
              (all-red clearance -> green hold per junction).

The trigger uses the ambulance's ground-truth position from SUMO, not
the detectors. That isolates "what is preemption worth" from "did the
CRNN hear the siren" -- phases 1-3 already measure the latter.

All numbers come from SUMO's tripinfo output. No assumed cycle times,
no analytical baselines:

  EV         corridor travel time, time stopped, number of stops
  civilians  mean/max time loss, mean waiting time, arrived count

Usage:
    python -m evaluation.counterfactual                    # 3 seeds, headless
    python -m evaluation.counterfactual --seeds 42 --gui
    python -m evaluation.counterfactual --duration 500 --depart 60

Writes:
    outputs/counterfactual/                  per-run cfg + tripinfo (disposable)
    evaluation/results/counterfactual.json   summary numbers (committed)
    docs/img/counterfactual_*.png            plots for the README (committed)
"""

